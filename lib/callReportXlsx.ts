import "server-only";
import ExcelJS from "exceljs";
import { CALL_SHEET_COLUMNS, type CallReport, type CallSummary } from "@/lib/callReport";
import { CALL_STATUSES, NOT_INTERESTED_REASONS, NEXT_ACTIONS, TEMPERATURES } from "@/lib/sales";

/**
 * Writes the Telecaller Daily Call Report workbook in the team's original
 * layout: Dashboard → Lists → one sheet per telecaller. Dashboard cells are
 * real Excel formulas (COUNTIFS/SUMIFS over the telecaller sheets, exactly
 * like the original), saved with their computed values so the numbers show
 * even in phone/email previews, and still recalculate if the From/To dates
 * on the Dashboard are changed.
 */

const NAVY = "FF1F3864";
const GREY_TEXT = "FF595959";
const TOTAL_FILL = "FFF2F2F2";
const DATE_FMT = "dd-mm-yyyy";

const toExcelDate = (ymd: string) => {
  const [y, m, d] = ymd.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d));
};

const ref = (sheet: string) => `'${sheet.replace(/'/g, "''")}'`;

function headerRow(ws: ExcelJS.Worksheet, row: number, labels: string[]) {
  labels.forEach((label, i) => {
    const c = ws.getCell(row, i + 1);
    c.value = label;
    c.font = { bold: true, color: { argb: "FFFFFFFF" } };
    c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: NAVY } };
    c.alignment = { vertical: "middle", wrapText: true };
  });
}

function sectionTitle(ws: ExcelJS.Worksheet, row: number, text: string) {
  const c = ws.getCell(row, 1);
  c.value = text;
  c.font = { bold: true, size: 12, color: { argb: NAVY } };
}

export async function callReportWorkbook(report: CallReport): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "SalesPulse";
  wb.created = new Date();
  wb.calcProperties.fullCalcOnLoad = true;

  const dash = wb.addWorksheet("Dashboard", { views: [{ state: "frozen", xSplit: 1, ySplit: 5 }] });
  const lists = wb.addWorksheet("Lists");

  // ── Lists (dropdown sources) ──────────────────────────────────────────────
  const listCols: [string, readonly string[]][] = [
    ["Lead Source", report.sources],
    ["Call Type", ["New Lead", "Follow-up"]],
    ["Call Status", CALL_STATUSES],
    ["Product", [...report.productNames, "None"]],
    ["Lead Type", ["Interested", "Not Interested"]],
    ["Temperature", TEMPERATURES],
    ["Reason", NOT_INTERESTED_REASONS],
    ["Next Action", NEXT_ACTIONS],
  ];
  listCols.forEach(([title, values], i) => {
    lists.getCell(1, i + 1).value = title;
    lists.getCell(1, i + 1).font = { bold: true };
    values.forEach((v, j) => (lists.getCell(j + 2, i + 1).value = v));
    lists.getColumn(i + 1).width = 24;
  });
  const listRange = (i: number) => {
    const col = String.fromCharCode(65 + i);
    return `Lists!$${col}$2:$${col}$${listCols[i][1].length + 1}`;
  };

  // ── One sheet per telecaller ──────────────────────────────────────────────
  const lastRows = new Map<string, number>();
  for (const t of report.telecallers) {
    const ws = wb.addWorksheet(t.user.sheetName, { views: [{ state: "frozen", xSplit: 3, ySplit: 3 }] });
    ws.getCell("A1").value = `Daily Call Report  -  ${t.user.name}`;
    ws.getCell("A1").font = { bold: true, size: 14, color: { argb: NAVY } };
    ws.getCell("A2").value =
      report.from === report.to
        ? `One row per call — ${report.from}. Generated by SalesPulse from logged calls.`
        : `One row per call — ${report.from} to ${report.to}. Generated by SalesPulse from logged calls.`;
    ws.getCell("A2").font = { italic: true, color: { argb: GREY_TEXT } };
    headerRow(ws, 3, CALL_SHEET_COLUMNS.map((c) => c.header));
    ws.getRow(3).height = 30;
    CALL_SHEET_COLUMNS.forEach((c, i) => (ws.getColumn(i + 1).width = c.width));

    t.rows.forEach((r, i) => {
      const row = ws.getRow(4 + i);
      row.values = [
        toExcelDate(r.date),
        r.customerName,
        r.phone,
        r.company,
        r.city,
        r.source,
        r.callType,
        r.callStatus,
        r.durationMins ?? null,
        r.product,
        r.leadType || null,
        r.temperature || null,
        r.reason || null,
        r.nextAction || null,
        r.followUpDate ? toExcelDate(r.followUpDate) : null,
        [r.time, r.remarks].filter(Boolean).join(" · "),
      ];
    });
    const last = Math.max(1003, 3 + t.rows.length + 200);
    lastRows.set(t.user.sheetName, last);
    ws.getColumn(1).numFmt = DATE_FMT;
    ws.getColumn(15).numFmt = DATE_FMT;
    ws.getColumn(3).numFmt = "@";
    ws.getColumn(9).numFmt = "0.0";

    // Same dropdowns as the original sheet, so rows can still be added/edited by hand.
    const dv = (col: string, listIdx: number) =>
      (ws as any).dataValidations.add(`${col}4:${col}${last}`, { type: "list", allowBlank: true, formulae: [listRange(listIdx)] });
    dv("F", 0);
    dv("G", 1);
    dv("H", 2);
    dv("J", 3);
    dv("K", 4);
    dv("L", 5);
    dv("M", 6);
    dv("N", 7);
    (ws as any).dataValidations.add(`I4:I${last}`, { type: "decimal", operator: "greaterThanOrEqual", allowBlank: true, formulae: [0] });

    const fillRule = (ref: string, text: string, argb: string, fontArgb: string) => ({
      type: "cellIs" as const,
      operator: "equal" as const,
      formulae: [`"${text}"`],
      style: { fill: { type: "pattern" as const, pattern: "solid" as const, bgColor: { argb } }, font: { color: { argb: fontArgb } } },
      priority: 1,
    });
    ws.addConditionalFormatting({
      ref: `K4:K${last}`,
      rules: [fillRule("", "Interested", "FFC6EFCE", "FF006100"), fillRule("", "Not Interested", "FFFFC7CE", "FF9C0006")],
    });
    ws.addConditionalFormatting({
      ref: `L4:L${last}`,
      rules: [fillRule("", "Hot", "FFFFC7CE", "FF9C0006"), fillRule("", "Warm", "FFFFEB9C", "FF9C5700"), fillRule("", "Cold", "FFDDEBF7", "FF1F4E78")],
    });
  }

  // ── Dashboard ─────────────────────────────────────────────────────────────
  const people = report.telecallers;
  const nCols = people.length + 2; // Metric + people + Team Total
  const totalCol = people.length + 2;
  const colLetter = (n: number) => {
    let s = "";
    while (n > 0) {
      const m = (n - 1) % 26;
      s = String.fromCharCode(65 + m) + s;
      n = Math.floor((n - 1) / 26);
    }
    return s;
  };
  dash.getColumn(1).width = 34;
  for (let i = 2; i <= nCols; i++) dash.getColumn(i).width = 14;

  dash.getCell("A1").value = "Telecaller Performance Dashboard";
  dash.getCell("A1").font = { bold: true, size: 16, color: { argb: NAVY } };
  dash.getCell("A3").value = "From date";
  dash.getCell("A4").value = "To date";
  dash.getCell("A3").font = dash.getCell("A4").font = { bold: true };
  for (const [addr, ymd] of [["B3", report.from], ["B4", report.to]] as const) {
    const c = dash.getCell(addr);
    c.value = toExcelDate(ymd);
    c.numFmt = DATE_FMT;
    c.font = { bold: true, color: { argb: "FF0000FF" } };
    c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFFFFF00" } };
  }
  dash.getCell("C3").value = "Report dates. Change them to recount any day within this file — the telecaller sheets hold every call in the exported range.";
  dash.getCell("C3").font = { italic: true, color: { argb: GREY_TEXT } };

  const range = (sheet: string, col: string) => `${ref(sheet)}!$${col}$4:$${col}$${lastRows.get(sheet)}`;
  const dateCrit = (sheet: string) => `${range(sheet, "A")},">="&$B$3,${range(sheet, "A")},"<="&$B$4`;
  const countIf = (sheet: string, col: string, value: string) => `COUNTIFS(${dateCrit(sheet)},${range(sheet, col)},"${value.replace(/"/g, '""')}")`;

  type Metric = {
    label: string;
    formula: (sheet: string, col: string) => string;
    value: (s: CallSummary) => number;
    numFmt?: string;
    totalFormula?: (col: string, row: number) => string;
  };

  let row = 6;
  const writeSection = (title: string, metrics: Metric[], values: (personIdx: number | "total", m: Metric) => number) => {
    sectionTitle(dash, row, title);
    row += 1;
    headerRow(dash, row, ["Metric", ...people.map((p) => p.user.name), "Team Total"]);
    row += 1;
    for (const m of metrics) {
      dash.getCell(row, 1).value = m.label;
      dash.getCell(row, 1).font = { bold: true };
      people.forEach((p, i) => {
        const c = dash.getCell(row, i + 2);
        c.value = { formula: m.formula(p.user.sheetName, colLetter(i + 2)), result: values(i, m) };
        c.numFmt = m.numFmt ?? "0";
      });
      const tc = dash.getCell(row, totalCol);
      const first = colLetter(2);
      const lastP = colLetter(totalCol - 1);
      tc.value = {
        formula: m.totalFormula ? m.totalFormula(colLetter(totalCol), row) : people.length ? `SUM(${first}${row}:${lastP}${row})` : "0",
        result: values("total", m),
      };
      tc.numFmt = m.numFmt ?? "0";
      tc.font = { bold: true };
      tc.fill = { type: "pattern", pattern: "solid", fgColor: { argb: TOTAL_FILL } };
      row += 1;
    }
  };

  const sumOf = (who: number | "total") => (who === "total" ? report.total.summary : people[who].summary);
  const rowsAt: Record<string, number> = {};
  const summaryMetrics: (Metric & { key: string })[] = [
    { key: "total", label: "Total Calls", formula: (s) => `COUNTIFS(${dateCrit(s)})`, value: (x) => x.totalCalls },
    { key: "connected", label: "Connected Calls", formula: (s) => countIf(s, "H", "Connected"), value: (x) => x.connected },
    { key: "notConnected", label: "Not Connected", formula: (_s, c) => `${c}${rowsAt.total}-${c}${rowsAt.connected}`, value: (x) => x.notConnected },
    { key: "newLeads", label: "New Leads Called", formula: (s) => countIf(s, "G", "New Lead"), value: (x) => x.newLeads },
    { key: "followUps", label: "Follow-up Calls", formula: (s) => countIf(s, "G", "Follow-up"), value: (x) => x.followUps },
    { key: "talk", label: "Total Talk Time (mins)", formula: (s) => `SUMIFS(${range(s, "I")},${dateCrit(s)})`, value: (x) => x.talkTime, numFmt: "0.0" },
    {
      key: "avg",
      label: "Avg Call Length - connected (mins)",
      formula: (_s, c) => `IFERROR(${c}${rowsAt.talk}/${c}${rowsAt.connected},0)`,
      value: (x) => x.avgConnected,
      numFmt: "0.0",
      totalFormula: (c) => `IFERROR(${c}${rowsAt.talk}/${c}${rowsAt.connected},0)`,
    },
    { key: "interested", label: "Interested", formula: (s) => countIf(s, "K", "Interested"), value: (x) => x.interested },
    { key: "notInterested", label: "Not Interested", formula: (s) => countIf(s, "K", "Not Interested"), value: (x) => x.notInterested },
    { key: "hot", label: "Hot Leads", formula: (s) => countIf(s, "L", "Hot"), value: (x) => x.hot },
    { key: "warm", label: "Warm Leads", formula: (s) => countIf(s, "L", "Warm"), value: (x) => x.warm },
    { key: "cold", label: "Cold Leads", formula: (s) => countIf(s, "L", "Cold"), value: (x) => x.cold },
    { key: "deals", label: "Deals Closed", formula: (s) => countIf(s, "N", "Deal Closed"), value: (x) => x.dealsClosed },
  ];
  // Row numbers are needed by the derived metrics, so assign them before writing.
  summaryMetrics.forEach((m, i) => (rowsAt[m.key] = row + 2 + i));
  writeSection("Call Summary (for selected dates)", summaryMetrics, (who, m) => m.value(sumOf(who)));

  // Rates, after a blank row — like the original.
  row += 1;
  for (const [label, num, den, get] of [
    ["Connect Rate", "connected", "total", (x: CallSummary) => x.connectRate],
    ["Interest Rate (of connected)", "interested", "connected", (x: CallSummary) => x.interestRate],
  ] as const) {
    dash.getCell(row, 1).value = label;
    dash.getCell(row, 1).font = { bold: true };
    for (let i = 0; i <= people.length; i++) {
      const col = i < people.length ? i + 2 : totalCol;
      const L = colLetter(col);
      const c = dash.getCell(row, col);
      c.value = { formula: `IFERROR(${L}${rowsAt[num]}/${L}${rowsAt[den]},0)`, result: get(i < people.length ? people[i].summary : report.total.summary) };
      c.numFmt = "0%";
      if (i === people.length) {
        c.font = { bold: true };
        c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: TOTAL_FILL } };
      }
    }
    row += 1;
  }

  row += 2;
  writeSection(
    "Product Interest (for selected dates)",
    report.productNames.map((name) => ({ label: name, formula: (s) => countIf(s, "J", name), value: () => 0 })),
    (who, m) => (who === "total" ? report.total.products[m.label] ?? 0 : people[who].products[m.label] ?? 0)
  );

  row += 2;
  writeSection(
    "Calls by Lead Source (for selected dates)",
    report.sources.map((src) => ({ label: src, formula: (s) => countIf(s, "F", src), value: () => 0 })),
    (who, m) => (who === "total" ? report.total.sources[m.label] ?? 0 : people[who].sources[m.label] ?? 0)
  );

  // Follow-ups due: live from SalesPulse (open follow-ups right now), not from the sheet rows —
  // a follow-up that has already been done shouldn't count as overdue.
  row += 2;
  sectionTitle(dash, row, "Follow-ups Due");
  row += 1;
  headerRow(dash, row, ["Metric", ...people.map((p) => p.user.name), "Team Total"]);
  row += 1;
  for (const [label, get, total] of [
    ["Due Today", (i: number) => people[i].dueToday, report.total.dueToday],
    ["Overdue (date passed)", (i: number) => people[i].overdue, report.total.overdue],
  ] as const) {
    dash.getCell(row, 1).value = label;
    dash.getCell(row, 1).font = { bold: true };
    people.forEach((_p, i) => (dash.getCell(row, i + 2).value = get(i)));
    const tc = dash.getCell(row, totalCol);
    tc.value = total;
    tc.font = { bold: true };
    tc.fill = { type: "pattern", pattern: "solid", fgColor: { argb: TOTAL_FILL } };
    row += 1;
  }
  dash.getCell(row, 1).value = `Note: Follow-ups Due shows open follow-ups in SalesPulse when this file was downloaded (${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC).`;
  dash.getCell(row, 1).font = { italic: true, color: { argb: GREY_TEXT } };

  // Sheet order matches the original: Dashboard, Lists, then one sheet per telecaller.
  const buf = await wb.xlsx.writeBuffer();
  return Buffer.from(buf as ArrayBuffer);
}
